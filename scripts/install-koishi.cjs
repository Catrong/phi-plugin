#!/usr/bin/env node
// 可放在仓库内运行，也可单独下载后在 Koishi 根目录运行。启动仅依赖 Node 内置模块。
const fs = require('node:fs')
const path = require('node:path')
const { createRequire } = require('node:module')
const { spawnSync } = require('node:child_process')

const REPOSITORY = 'https://github.com/Catrong/phi-plugin.git'
const WRAPPER_NAME = 'koishi-plugin-phi-plugin'
const WRAPPER_ENTRY = "// Generated by phi-plugin/scripts/install-koishi.cjs\nmodule.exports = require('phi-plugin/koishi')\n"

function parseArgs(args) {
    const options = { root: process.cwd(), repo: REPOSITORY, branch: '', config: 'koishi.yml', update: false, dryRun: false, manager: '', renderer: '' }
    for (let i = 0; i < args.length; i++) {
        const arg = args[i]
        if (arg === '--help' || arg === '-h') return { ...options, help: true }
        if (arg === '--update') options.update = true
        else if (arg === '--dry-run') options.dryRun = true
        else if (['--root', '--repo', '--branch', '--config', '--manager', '--renderer'].includes(arg)) {
            if (!args[i + 1] || args[i + 1].startsWith('--')) throw new Error(`${arg} 缺少参数`)
            options[arg.slice(2)] = args[++i]
        } else throw new Error(`未知参数：${arg}`)
    }
    if (options.manager && !['npm', 'yarn', 'pnpm'].includes(options.manager)) throw new Error('--manager 仅支持 npm、yarn、pnpm')
    if (options.renderer && !['puppeteer', 'shotium', 'auto'].includes(options.renderer)) throw new Error('--renderer 仅支持 puppeteer、shotium、auto')
    return options
}

function run(command, args, cwd, capture = false) {
    // Windows 的包管理器是 .cmd；仅这些固定命令使用 shell，不插入路径或用户参数。
    const packageManager = ['npm', 'yarn', 'pnpm'].includes(command)
    const result = spawnSync(command, args, {
        cwd,
        shell: process.platform === 'win32' && packageManager,
        stdio: capture ? 'pipe' : 'inherit',
        encoding: 'utf8',
        env: { ...process.env, PUPPETEER_SKIP_DOWNLOAD: 'true' },
    })
    if (result.error) throw new Error(`无法执行 ${command}：${result.error.message}`)
    if (result.status !== 0) throw new Error(`${command} 执行失败（退出码 ${result.status}）`)
    return result.stdout || ''
}

function detectManager(root, manifest) {
    const locks = [['package-lock.json', 'npm'], ['yarn.lock', 'yarn'], ['pnpm-lock.yaml', 'pnpm']]
        .filter(([file]) => fs.existsSync(path.join(root, file)))
    if (locks.length === 1) return locks[0][1]
    if (locks.length > 1) throw new Error('存在多种宿主锁文件，请通过 --manager 明确选择包管理器')
    const manager = (manifest.packageManager || '').split('@')[0]
    return ['npm', 'yarn', 'pnpm'].includes(manager) ? manager : 'npm'
}

function readJson(file) {
    return JSON.parse(fs.readFileSync(file, 'utf8'))
}

function loadYaml(root, core) {
    for (const base of [root, core]) {
        try { return createRequire(path.join(base, 'package.json'))('yaml') } catch (error) {
            if (error.code !== 'MODULE_NOT_FOUND') throw error
        }
    }
    const error = new Error('无法加载 yaml，请检查包管理器输出')
    error.code = 'PHI_YAML_UNAVAILABLE'
    throw error
}

// 递归检查分组，只匹配插件键，绝不搜索/输出配置中的密钥等值。
function findEntries(YAML, plugins, predicate, enabled = true, result = []) {
    if (!YAML.isMap(plugins)) throw new Error('plugins 必须是 YAML 映射')
    for (const pair of plugins.items) {
        const key = String(pair.key.value)
        const name = key.replace(/^~/, '').split(':')[0]
        const active = enabled && !key.startsWith('~') && pair.value?.get?.('$if') !== false
        if (name === 'group') findEntries(YAML, pair.value, predicate, active, result)
        else if (predicate(name)) result.push({ pair, name, active })
    }
    return result
}

function configure(YAML, source, renderer = '') {
    const doc = YAML.parseDocument(source)
    if (doc.errors.length) throw new Error('Koishi YAML 配置存在语法错误，请先修复')
    if (!YAML.isMap(doc.contents)) throw new Error('Koishi 配置必须是 YAML 映射')
    if (!doc.has('plugins')) doc.set('plugins', {})
    const plugins = doc.get('plugins', true)
    const existing = findEntries(YAML, plugins, name => name === 'phi-plugin' || /(?:^|\/)phi-plugin\/koishi\.cjs$/.test(name))
    if (existing.length > 1) throw new Error('发现多个 phi-plugin 配置项，请先合并，避免重复响应')
    if (!existing.length) plugins.set('phi-plugin', {})
    else if (existing[0].name !== 'phi-plugin') {
        // 从旧的相对路径入口迁移，保留禁用标记、实例 ID 和完整配置。
        existing[0].pair.key.value = String(existing[0].pair.key.value).replace(existing[0].name, 'phi-plugin')
    }
    let settings = existing.length ? existing[0].pair.value : plugins.get('phi-plugin', true)
    const configuredRenderer = YAML.isMap(settings) ? settings.get('renderer') : undefined
    const selectedRenderer = renderer || configuredRenderer || 'puppeteer'
    if (!['puppeteer', 'shotium', 'auto'].includes(selectedRenderer)) throw new Error('渲染器仅支持 puppeteer、shotium、auto，请修正 phi-plugin 的 renderer 配置')
    if (renderer) {
        if (!YAML.isMap(settings)) {
            if (settings && settings.value != null) throw new Error('phi-plugin 配置必须是 YAML 映射')
            settings = doc.createNode({})
            if (existing.length) existing[0].pair.value = settings
            else plugins.set('phi-plugin', settings)
        }
        settings.set('renderer', selectedRenderer)
    }
    const puppeteer = findEntries(YAML, plugins, name => name === 'puppeteer')
    if (selectedRenderer !== 'shotium' && !puppeteer.length) plugins.set('puppeteer', {})
    const database = findEntries(YAML, plugins, name => name.startsWith('database-'))
    const notices = []
    if (existing.length && !existing[0].active) notices.push('已有 phi-plugin 处于禁用分组或禁用状态，已保留；请在控制台启用。')
    if (selectedRenderer !== 'shotium' && puppeteer.length && !puppeteer.some(item => item.active)) notices.push('Puppeteer 服务已配置但未启用，请在控制台启用。')
    if (!database.some(item => item.active)) notices.push('请在控制台启用一个 database 服务（例如 database-sqlite）。')
    return { content: doc.toString(), notices, renderer: selectedRenderer }
}

function addRendererDependencies(host, renderer, coreMeta) {
    const existing = { ...host.devDependencies, ...host.dependencies }
    const packages = {}
    if (renderer !== 'puppeteer') packages['@pixel.js/shotium'] = coreMeta.peerDependencies?.['@pixel.js/shotium'] || '^0.12.2'
    if (renderer !== 'shotium') {
        packages['koishi-plugin-puppeteer'] = '^3.9.0'
        packages.puppeteer = coreMeta.peerDependencies?.puppeteer || coreMeta.dependencies?.puppeteer || '^24.16.2'
    }
    let changed = false
    for (const [name, version] of Object.entries(packages)) {
        if (existing[name]) continue
        host.dependencies[name] = version
        changed = true
    }
    return changed
}

function verifyInstallation(root) {
    const requireHost = createRequire(path.join(root, 'package.json'))
    const meta = requireHost(`${WRAPPER_NAME}/package.json`)
    if (meta.name !== WRAPPER_NAME) throw new Error('包装包名称不匹配，控制台无法识别')
    const wrapper = requireHost(WRAPPER_NAME)
    if (wrapper !== requireHost('phi-plugin/koishi') || typeof wrapper.apply !== 'function' || !wrapper.Config) {
        throw new Error('包装入口或 Config 导出验证失败')
    }
}

function install(options, dependencies = {}) {
    const execute = dependencies.run || run
    const root = fs.realpathSync(path.resolve(options.root))
    const hostFile = path.join(root, 'package.json')
    const host = readJson(hostFile)
    const deps = { ...host.devDependencies, ...host.dependencies }
    if (!deps.koishi && !deps['@koishijs/core']) throw new Error('目标目录不是 Koishi 项目，请使用 --root 指定宿主根目录')
    const configFile = path.resolve(root, options.config)
    if (!fs.existsSync(configFile)) throw new Error(`配置文件不存在：${configFile}；可通过 --config 指定 YAML 配置`)
    if (!/\.ya?ml$/i.test(configFile)) throw new Error('目前只支持 YAML 格式的 Koishi 配置')
    const core = path.join(root, 'external', 'phi-plugin')
    const wrapper = path.join(root, 'external', WRAPPER_NAME)
    const wrapperFile = path.join(wrapper, 'package.json')
    const entryFile = path.join(wrapper, 'index.cjs')
    if (fs.existsSync(wrapper)) {
        if (!fs.existsSync(wrapperFile) || readJson(wrapperFile).name !== WRAPPER_NAME
            || !fs.existsSync(entryFile) || !/module\.exports\s*=\s*require\(['"]phi-plugin\/koishi['"]\)/.test(fs.readFileSync(entryFile, 'utf8'))) {
            throw new Error(`包装目录已被其他代码占用：${wrapper}；请先迁移旧插件，安装器不会覆盖`)
        }
    }
    if (fs.existsSync(core) && (!fs.existsSync(path.join(core, 'package.json')) || readJson(path.join(core, 'package.json')).name !== 'phi-plugin')) {
        throw new Error(`插件目录被其他内容占用：${core}`)
    }
    const manager = options.manager || detectManager(root, host)
    console.log(`Koishi：${root}\n本体：${core}\n包装包：${wrapper}\n包管理器：${manager}`)
    if (options.dryRun) {
        console.log(`预览：${fs.existsSync(core) ? options.update ? '快进更新本体' : '复用已有本体' : '克隆本体'} → 生成包装包 → 安装${options.renderer || '已有配置指定的'}渲染器依赖 → 登记配置。未写入文件。`)
        return
    }
    if (manager === 'yarn') {
        if (Number(execute('yarn', ['--version'], root, true).trim().split('.')[0]) < 2) {
            throw new Error('需要 Yarn 2+ 的 portal 本地链接支持；也可使用 --manager npm')
        }
        if (execute('yarn', ['config', 'get', 'nodeLinker'], root, true).trim() !== 'node-modules') {
            throw new Error('Koishi 包扫描需要 node_modules，请先将 Yarn nodeLinker 设置为 node-modules')
        }
    }
    if (manager === 'pnpm' && Number(execute('npm', ['--version'], root, true).trim().split('.')[0]) < 7) {
        throw new Error('pnpm 本地链接的公共依赖安装需要 npm 7+（随 Node.js 提供），请先升级 Node.js / npm')
    }
    if (!fs.existsSync(core)) {
        fs.mkdirSync(path.dirname(core), { recursive: true })
        execute('git', ['clone', '--depth=1', ...(options.branch ? ['--branch', options.branch] : []), '--', options.repo, core], root)
    } else if (options.update) {
        if (!fs.existsSync(path.join(core, '.git'))) throw new Error('本体不是 Git 仓库，不能自动更新')
        if (execute('git', ['status', '--porcelain'], core, true).trim()) throw new Error('本体有未提交修改，已停止更新；提交或保存修改后重试')
        execute('git', ['pull', '--ff-only'], core)
    }
    const coreMeta = readJson(path.join(core, 'package.json'))
    if (coreMeta.name !== 'phi-plugin' || !fs.existsSync(path.join(core, 'koishi.cjs'))) throw new Error('该 phi-plugin 版本没有 Koishi 入口，请更新到支持双平台的版本')
    const before = fs.readFileSync(path.join(core, 'package.json'))
    const source = fs.readFileSync(configFile, 'utf8')
    let YAML, configured
    try {
        YAML = (dependencies.loadYaml || loadYaml)(root, core)
    } catch (error) {
        if (error.code !== 'PHI_YAML_UNAVAILABLE') throw error
    }
    if (YAML) configured = configure(YAML, source, options.renderer)
    const backup = path.join(root, '.phi-plugin-install-backups', `${Date.now()}-${process.pid}`)
    fs.mkdirSync(backup, { recursive: true, mode: 0o700 })
    for (const [label, file] of [
        ['package.json', hostFile], ['koishi.yml', configFile], ['wrapper-package.json', wrapperFile], ['wrapper-index.cjs', entryFile],
        ...['package-lock.json', 'yarn.lock', 'pnpm-lock.yaml'].map(name => [name, path.join(root, name)]),
    ]) {
        if (fs.existsSync(file)) fs.writeFileSync(path.join(backup, label), fs.readFileSync(file), { mode: 0o600 })
    }
    console.log(`原文件备份：${backup}`)
    const protocol = manager === 'yarn' ? 'portal:' : manager === 'pnpm' ? 'link:' : 'file:'
    fs.mkdirSync(wrapper, { recursive: true })
    fs.writeFileSync(wrapperFile, JSON.stringify({
        name: WRAPPER_NAME, version: coreMeta.version, private: true,
        description: 'phi-plugin 的 Koishi 本地包装入口', main: 'index.cjs', license: coreMeta.license || 'ISC',
        dependencies: { 'phi-plugin': `${protocol}../phi-plugin` },
        peerDependencies: { koishi: '^4.18.11' },
        koishi: { service: { required: ['database'], optional: ['puppeteer'] } },
    }, null, 2) + '\n')
    fs.writeFileSync(entryFile, WRAPPER_ENTRY)
    host.dependencies ||= {}
    host.dependencies[WRAPPER_NAME] = `${protocol}./external/${WRAPPER_NAME}`
    host.dependencies['phi-plugin'] = `${protocol}./external/phi-plugin`
    if (configured) addRendererDependencies(host, configured.renderer, coreMeta)
    fs.writeFileSync(hostFile, JSON.stringify(host, null, 2) + '\n')
    // pnpm link 不安装本体依赖；npm 仅补齐公共运行依赖，跳过根项目 peers，避免安装未选后端。
    // 不生成本体 npm 锁文件，也不改动本体 manifest / pnpm 锁文件；宿主继续使用其原包管理器。
    if (manager === 'pnpm') execute('npm', ['install', '--omit=dev', '--omit=peer', '--package-lock=false', '--ignore-scripts', '--no-audit', '--no-fund'], core)
    execute(manager, manager === 'npm' ? ['install', '--ignore-scripts', '--no-audit', '--no-fund'] : ['install'], root)
    if (!before.equals(fs.readFileSync(path.join(core, 'package.json')))) throw new Error('包管理器修改了本体 package.json，请检查安装结果与备份')
    if (!configured) {
        // 冷安装先取得公共 YAML 解析器，再决定后端，避免把已有 Shotium 实例改回 Puppeteer。
        YAML = (dependencies.loadYaml || loadYaml)(root, core)
        configured = configure(YAML, source, options.renderer)
        if (addRendererDependencies(host, configured.renderer, coreMeta)) {
            fs.writeFileSync(hostFile, JSON.stringify(host, null, 2) + '\n')
            execute(manager, manager === 'npm' ? ['install', '--ignore-scripts', '--no-audit', '--no-fund'] : ['install'], root)
        }
    }
    ;(dependencies.verify || verifyInstallation)(root)
    if (fs.readFileSync(configFile, 'utf8') !== source) throw new Error('Koishi 配置在安装期间发生变化，已保留新配置；依赖已安装，请重新运行安装器登记渲染器')
    if (source !== configured.content) fs.writeFileSync(configFile, configured.content)
    console.log(`安装完成：包装包、插件入口和配置表单已验证，渲染器为 ${configured.renderer}。请重启 Koishi 并刷新 WebUI。`)
    for (const notice of configured.notices) console.log(notice)
}

if (require.main === module) {
    try {
        const options = parseArgs(process.argv.slice(2))
        if (options.help) console.log(`用法：node install-koishi.cjs [--root Koishi目录] [--renderer puppeteer|shotium|auto] [--update] [--dry-run]\n  --repo URL       首次安装的 Git 仓库（默认 ${REPOSITORY}）\n  --branch 分支    首次克隆指定分支，默认使用远端默认分支\n  --config 文件    相对宿主目录的 YAML 配置，默认 koishi.yml\n  --manager 名称   npm / yarn（2+）/ pnpm；默认优先使用唯一锁文件\n  --renderer 名称 安装并选择对应渲染器；auto 准备两个后端，省略时保留已有配置，首次安装默认 puppeteer\n已有本体默认不更新；--update 仅允许干净工作区快进更新。本体 package.json 不作改动。`)
        else install(options)
    } catch (error) {
        console.error(`安装失败：${error.message}\n如已生成备份，可在宿主 .phi-plugin-install-backups 目录恢复原配置。`)
        process.exitCode = 1
    }
}

module.exports = { parseArgs, detectManager, configure, install, verifyInstallation }
